// Sprachnotizen – Service Worker
// Cacht die App-Hülle, damit die App auch ohne Internet startet und
// diktierte Einträge lokal entgegennimmt. Die Synchronisation mit Google
// passiert separat, sobald wieder eine Verbindung besteht (siehe app.js).

const CACHE_VERSION = "sprachnotizen-v1";
const APP_SHELL = [
  "./",
  "./index.html",
  "./styles.css",
  "./app.js",
  "./manifest.webmanifest",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
  "./icons/apple-touch-icon.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_VERSION).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((key) => key !== CACHE_VERSION)
          .map((key) => caches.delete(key))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);

  // Nie Google-API-Aufrufe oder fremde Origins aus dem Cache bedienen –
  // die müssen immer live gehen (oder sichtbar fehlschlagen, damit die
  // App sie in die Warteschlange legen kann).
  if (url.origin !== self.location.origin) {
    return;
  }

  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_VERSION).then((cache) => cache.put(event.request, copy));
          return response;
        })
        .catch(() => cached);
    })
  );
});
